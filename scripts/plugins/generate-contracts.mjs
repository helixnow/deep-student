// Small, deliberately bounded JSON Schema -> TS generator for the pilot wire contract.
// Unknown shapes fail instead of silently widening a contract to `any`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const schema = JSON.parse(fs.readFileSync(path.join(root, 'contracts/translation/v1.json'), 'utf8'));
function type(s) {
  if (s.$ref) return s.$ref.split('/').at(-1);
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((x) => JSON.stringify(x)).join(' | ');
  if (Array.isArray(s.type)) {
    if (s.type.length !== 2 || !s.type.includes('null')) throw new Error('Unsupported union');
    return `${type({ ...s, type: s.type.find((t) => t !== 'null') })} | null`;
  }
  if (s.type === 'array') {
    if (Array.isArray(s.items)) {
      if (s.minItems !== s.items.length || s.maxItems !== s.items.length) throw new Error('Unbounded tuple');
      return `[${s.items.map((x) => type(x)).join(', ')}]`;
    }
    return `Array<${type(s.items)}>`;
  }
  const primitives = { string: 'string', boolean: 'boolean', integer: 'number' };
  if (primitives[s.type]) return primitives[s.type];
  throw new Error(`Unsupported schema: ${JSON.stringify(s)}`);
}
function fields(s) {
  return Object.entries(s.properties)
    .map(([k, value]) => `  ${k}${(s.required ?? []).includes(k) ? '' : '?'}: ${type(value)};`).join('\n');
}
const ts = ['// Generated by scripts/plugins/generate-contracts.mjs; edit contracts/translation/v1.json.'];
for (const [name, s] of Object.entries(schema.definitions)) {
  if (s.oneOf) ts.push(`export type ${name} =\n${s.oneOf.map((v) => `{\n${fields(v)}\n}`).join(' | ')};`);
  else if (s.enum) ts.push(`export type ${name} = ${type(s)};`);
  else ts.push(`export interface ${name} {\n${fields(s)}\n}`);
}
const outputs = [
  ['src/plugin-runtime/contracts/translation.ts', ts.join('\n\n') + '\n'],
];
let stale = false;
for (const [name, content] of outputs) {
  const target = path.join(root, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
      console.error(`Stale generated contract: ${name}`);
      stale = true;
    }
  } else if (process.argv.includes('--patch')) {
    console.log(`*** Begin Patch\n*** Add File: ${name}\n${content.trimEnd().split('\n').map((line) => '+' + line).join('\n')}\n*** End Patch`);
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
}
if (stale) process.exitCode = 1;
