#!/usr/bin/env node
/**
 * 社区插件脚手架：按插件 id 生成一个能直接装载、能通过 examples/testing/conformance.ts 全部检查的 v1 插件包。
 *
 *   node examples/scripts/create-plugin.mjs <id> [--out <目录>] [--app <应用仓库根>] [--host-only] [--force]
 *
 * 生成：package.json（v1 清单）、index.ts（Host 半）、ui.tsx 与 i18n.ts（UI 半，--host-only 时不生成）、
 * test.profile.json / user.profile.json、__tests__/<name>.test.ts[x]、README.md、.gitignore。
 * 服务名等由 id 派生的名字直接用 host/kernel/plugin-id.ts 计算，与 Host 装载时的检查同一份代码。
 *
 * Host 半与测试经相对路径导入应用仓库里的 host/kernel/api.ts 与 examples/testing/harness.ts（同仓库内示例的写法），
 * build:ui 调用仓库里的 examples/scripts/build-ui.mjs：Host 目前没有给社区模块提供导入内核 API 的运行时模块名，
 * 所以生成的插件要放在应用仓库旁边开发。生成的 README 里的命令由 examples/scripts/__tests__/walkthrough.test.tsx 原样执行。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const DEFAULT_APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const VERSION = '0.1.0';

export class CreatePluginError extends Error {}

/** 应用里的 host/kernel/plugin-id.ts（Node 原生类型擦除导入；vitest 下照常转换）。 */
async function pluginIdModule(app) {
  return import(pathToFileURL(path.join(app, 'host/kernel/plugin-id.ts')).href);
}

const words = (text) => text.split(/[.-]/).filter(Boolean);
const titleCase = (name) => words(name).map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
const pascalCase = (service) => service[0].toUpperCase() + service.slice(1);

/** 从 `from` 目录到 `to` 的相对导入路径（总是 `./` 或 `../` 开头、正斜杠）。 */
function relativeImport(from, to) {
  const rel = path.relative(from, to).split(path.sep).join('/');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

function packageJson({ id, name, publisher, engines, hostOnly, buildUi }) {
  const deepStudent = { manifestVersion: 1, id, platforms: ['desktop'], host: './index.ts', ...(hostOnly ? {} : { ui: './dist/ui.js' }) };
  return json({
    name: publisher === 'example' ? `deepstudent-plugin-${name}` : `@${publisher}/deepstudent-plugin-${name}`,
    version: VERSION,
    private: true,
    description: `${titleCase(name)}: Deep Student community plugin (generated by examples/scripts/create-plugin.mjs)`,
    type: 'module',
    engines: { deepStudent: engines },
    deepStudent,
    // 构建脚本在应用仓库里（examples/scripts/build-ui.mjs），用仓库的 esbuild。
    ...(hostOnly ? {} : { scripts: { 'build:ui': `node ${buildUi}` } }),
  });
}

function hostHalf({ id, service, kernelApi, hostOnly }) {
  const Service = `${pascalCase(service)}Service`;
  return `/**
 * Host 半：提供 \`${service}\` 服务（由 id 派生的服务名，host/kernel/plugin-id.ts 的 pluginServiceName）。
${hostOnly ? '' : ` * meta.remote 只把 \`greet\` 开放给 UI 半（经 plugin:host|call），其他方法 UI 调不到。\n`} * meta.id、meta.version 必须等于 package.json 的 deepStudent.id、version。
 */
import { CommandError, definePlugin } from '${kernelApi}';

export interface ${Service} {
  greet(name: string): string;
}

declare module '@deepseek-ai/cordis' {
  interface Context {
    ${service}: ${Service};
  }
}

export default definePlugin({
  meta: {
    id: '${id}',
    version: '${VERSION}',
    platforms: ['desktop'],
    provides: ['${service}'],
${hostOnly ? '' : `    ui: './dist/ui.js',\n    remote: { ${service}: ['greet'] },\n`}  },
  apply(ctx) {
    const service: ${Service} = {
      greet(name) {
        if (typeof name !== 'string' || name.trim() === '') throw new CommandError('name is required');
        return \`Hello, \${name.trim()}\`;
      },
    };
    ctx.provide('${service}', service);
  },
});
`;
}

function i18nModule({ title }) {
  return `/** 文案登记在由插件 id 派生的命名空间（ctx.ui.i18n.addBundles）；zh-CN 与 en-US 都要有。 */
export const messages = {
  'zh-CN': { title: '${title}', open: '打开 ${title}', loading: '加载中…', failed: '加载失败：{{reason}}' },
  'en-US': { title: '${title}', open: 'Open ${title}', loading: 'Loading…', failed: 'Failed to load: {{reason}}' },
};
`;
}

function uiHalf({ id, service }) {
  return `/**
 * UI 半：侧栏导航项 + 视图 + 命令面板命令；视图经 ctx.ui.host 调 Host 半的 \`greet\`。
 * 只从 react 与 @deepstudent/ui 导入（宿主经 import map 只共享 react、react-dom、@deepstudent/ui、i18next）。
 */
import React, { useEffect, useState } from 'react';
import { definePlugin, useT, withPluginScope } from '@deepstudent/ui';
import { messages } from './i18n';

export const PLUGIN_ID = '${id}';
/** 槽位贡献 id：\`<id>/<localId>\`。 */
export const VIEW_ID = \`\${PLUGIN_ID}/main\`;
/** 命令 id：\`{module}.{action}\`，module 用插件 id。 */
export const OPEN_COMMAND_ID = \`\${PLUGIN_ID}.open\`;

function reasonOf(error: unknown): string {
  if (typeof error === 'object' && error !== null && 'message' in error) return String((error as { message: unknown }).message);
  return String(error);
}

export function MainView({ load }: { load: () => Promise<string> }) {
  const t = useT();
  const [text, setText] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    load().then(setText, (e: unknown) => setError(reasonOf(e)));
  }, [load]);
  if (error) return <p role="alert">{t('failed', { reason: error })}</p>;
  return <p>{text ?? t('loading')}</p>;
}

export default definePlugin({
  meta: { id: PLUGIN_ID, version: '${VERSION}', host: true },
  apply(ctx) {
    ctx.ui.i18n.addBundles(messages);
    const ns = ctx.ui.i18n.namespace;
    const load = () => ctx.ui.host.${service}!.greet!('Deep Student') as Promise<string>;
    // 视图由外壳渲染（不经 <SlotOutlet>），用 withPluginScope 让组件里的 useT 找到本插件。
    const View = withPluginScope(ctx, () => <MainView load={load} />);
    ctx.ui.views.register({ id: VIEW_ID, titleKey: \`\${ns}:title\`, component: View });
    ctx.ui.nav.register({ id: VIEW_ID, viewId: VIEW_ID, labelKey: \`\${ns}:title\`, order: 900 });
    ctx.ui.commands.register({ id: OPEN_COMMAND_ID, name: \`\${ns}:open\`, category: 'navigation', execute: () => ctx.ui.navigate(VIEW_ID) });
  },
});
`;
}

function testFile({ id, service, harness, hostOnly }) {
  const head = `// @vitest-environment node
/** ${id}：Host 半经真实 profile 装载器（含社区清单筛查）装进测试宿主${hostOnly ? '' : '，UI 半装进真实 UI 内核，二者经 plugin:host|call 连接'}。 */
import { fileURLToPath } from 'node:url';
import { afterEach, describe, expect, it } from 'vitest';
import { ${hostOnly ? '' : 'createUiKernel, installUiHalf, '}loadExample${hostOnly ? '' : ', renderView'} } from '${harness}';
${hostOnly ? '' : "import uiHalf, { OPEN_COMMAND_ID, VIEW_ID } from '../ui';\n"}
const ID = '${id}';
const PROFILE = fileURLToPath(new URL('../test.profile.json', import.meta.url));

const cleanups: (() => Promise<void>)[] = [];
afterEach(async () => {
  for (const cleanup of cleanups.splice(0).reverse()) await cleanup();
});

async function setup() {
  const loaded = await loadExample(PROFILE);
  cleanups.push(() => loaded.host.dispose());
  return loaded;
}

describe(ID, () => {
  it('passes the community manifest screening and provides ${service}', async () => {
    const { host, result } = await setup();
    expect(result.degraded).toEqual([]);
    expect(result.installed.map((p) => p.id)).toEqual([ID]);
    expect(host.ctx.get('${service}')!.greet('Ada')).toBe('Hello, Ada');
    expect(() => host.ctx.get('${service}')!.greet(' ')).toThrow();
  });
`;
  const ui = `
  it('UI half contributes a view, a nav item and a command, and calls the Host half', async () => {
    const { host } = await setup();
    const { kernel, commands } = createUiKernel(host, { i18n: { addBundle: () => () => undefined } });
    cleanups.push(() => kernel.dispose());
    // ctx.ui.host 的调用带上本插件 id，只能在插件里拿到：installUiHalf 交出 UI 半在 apply 里拿到的那个。
    const { installed, host: remoteHost } = await installUiHalf(kernel, uiHalf);
    expect(installed).toBe(true);
    expect(kernel.slots.list('views').map((e) => [e.key, e.owner, e.origin])).toEqual([[VIEW_ID, ID, 'community']]);
    expect(kernel.slots.list('nav').map((e) => e.value.viewId)).toEqual([VIEW_ID]);
    expect(commands.list().map((c) => c.id)).toEqual([OPEN_COMMAND_ID]);
    const remote = remoteHost.${service}!;
    await expect(remote.greet!('Ada')).resolves.toBe('Hello, Ada');
    await expect(remote.greet!('')).rejects.toBe('name is required');
    await expect(remote.notExposed!()).rejects.toMatchObject({ error_type: 'Validation' });

    await kernel.unload(ID);
    expect(kernel.slots.list('views')).toEqual([]);
    expect(commands.list()).toEqual([]);
  });

  it('renders its view the way the shell does, with the text from the Host half', async () => {
    const { host } = await setup();
    const { kernel } = createUiKernel(host, { i18n: { addBundle: () => () => undefined } });
    cleanups.push(() => kernel.dispose());
    expect(await kernel.install(uiHalf)).toBe(true);
    const view = await renderView(kernel, VIEW_ID);
    cleanups.push(async () => view.unmount());
    expect(await view.findByText('Hello, Deep Student')).toBeTruthy();
  });
`;
  const tail = `
  it('removes its service on unload', async () => {
    const { host } = await setup();
    await host.unload(ID);
    expect(host.ctx.get('${service}')).toBeUndefined();
  });
});
`;
  return head + (hostOnly ? '' : ui) + tail;
}

/** POSIX shell 里原样使用的路径：只含安全字符时不加引号，否则用单引号括起来。 */
function shellPath(p) {
  return /^[\w./-]+$/.test(p) ? p : `'${p.replaceAll("'", `'\\''`)}'`;
}

