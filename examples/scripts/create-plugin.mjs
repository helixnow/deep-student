/**
 * 生成插件包，返回 `{ out, files }`（相对 out 的文件列表）。不合法或保留的 id、已存在的非空目录（未给 force）抛
 * {@link CreatePluginError}。
 */
export async function createPlugin({ id, out, app = DEFAULT_APP, hostOnly = false, force = false }) {
  const { isValidPluginId, parsePluginId, reservedIdProblem, pluginNamespaces } = await pluginIdModule(app);
  if (!isValidPluginId(id)) {
    throw new CreatePluginError(`invalid plugin id ${JSON.stringify(id)}: use <publisher>.<name> (lowercase, [a-z0-9-]); publishers ds, deepstudent, deep-student, official, builtin, system, community are forbidden`);
  }
  const reserved = reservedIdProblem(id, 'community-startup');
  if (reserved) throw new CreatePluginError(`plugin id "${id}": ${reserved}`);
  const { publisher, name } = parsePluginId(id);
  const { service } = pluginNamespaces(id);

  const target = path.resolve(out ?? name);
  if (fs.existsSync(target) && fs.readdirSync(target).length > 0 && !force) {
    throw new CreatePluginError(`${target} is not empty (pass --force to overwrite)`);
  }
  fs.mkdirSync(path.join(target, '__tests__'), { recursive: true });
  // Node 按真实路径解析 ESM（macOS 的 /tmp 是 /private/tmp 的软链），相对导入必须从真实路径算。
  const real = fs.realpathSync(target);
  const appReal = fs.realpathSync(app);
  const appVersion = JSON.parse(fs.readFileSync(path.join(appReal, 'package.json'), 'utf8')).version;
  const [major, minor] = appVersion.split('.');
  const context = {
    id, name, publisher, service, hostOnly, title: titleCase(name), engines: `^${major}.${minor}`, app: appReal, out: real,
    buildUi: relativeImport(real, path.join(appReal, 'examples/scripts/build-ui.mjs')),
  };

  const files = {
    'package.json': packageJson(context),
    'index.ts': hostHalf({ ...context, kernelApi: relativeImport(real, path.join(appReal, 'host/kernel/api.ts')) }),
    'test.profile.json': json({ $comment: '测试用：只装本插件（不 extends 官方 profile）。', plugins: [{ id, module: './index.ts' }] }),
    'user.profile.json': json({
      $comment: '用户 profile：放在 <应用数据目录>/plugins/user.profile.json，在官方插件之外装载本插件（host/kernel/profile.ts loadStartupProfile）。',
      extends: 'official',
      plugins: [{ id, module: path.join(real, 'index.ts') }],
    }),
    [`__tests__/${name}.test.${hostOnly ? 'ts' : 'tsx'}`]: testFile({ ...context, harness: relativeImport(path.join(real, '__tests__'), path.join(appReal, 'examples/testing/harness.ts')) }),
    'README.md': readme(context),
    '.gitignore': 'dist/\nnode_modules/\n',
    ...(hostOnly ? {} : { 'ui.tsx': uiHalf(context), 'i18n.ts': i18nModule(context) }),
  };
  for (const [file, text] of Object.entries(files)) fs.writeFileSync(path.join(real, file), text);
  return { out: real, files: Object.keys(files).sort() };
}

function parseArgs(argv) {
  const args = { hostOnly: false, force: false };
  const rest = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--host-only') args.hostOnly = true;
    else if (a === '--force') args.force = true;
    else if (a === '--out' || a === '--app') args[a.slice(2)] = argv[++i];
    else if (a.startsWith('--')) throw new CreatePluginError(`unknown option ${a}`);
    else rest.push(a);
  }
  if (rest.length !== 1) throw new CreatePluginError('usage: node examples/scripts/create-plugin.mjs <id> [--out <dir>] [--app <app repo>] [--host-only] [--force]');
  return { ...args, id: rest[0] };
}

// import.meta.url 是真实路径；命令行给的路径可能经过软链（macOS 的 /tmp、软链出来的仓库目录）。
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  try {
    const { out, files } = await createPlugin(parseArgs(process.argv.slice(2)));
    console.log(`created ${out}\n${files.map((f) => `  ${f}`).join('\n')}`);
  } catch (error) {
    if (!(error instanceof CreatePluginError)) throw error;
    console.error(error.message);
    process.exitCode = 1;
  }
}
