import { createPublicKey, verify } from 'node:crypto';
import { isUtf8 } from 'node:buffer';
import { blake2b } from '@noble/hashes/blake2b';

const invalid = () => new Error('Invalid encoding in minisign data');
function decode(value: string): Buffer {
  if (!/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(value)) throw invalid();
  return Buffer.from(value, 'base64');
}
function text(value: string): string {
  const bytes = decode(value);
  if (!isUtf8(bytes)) throw new Error(`The signature ${value} could not be decoded, please check if it is a valid base64 string. The signature must be the contents of the \`.sig\` file generated by the Tauri bundler, as a string.`);
  return bytes.toString('utf8');
}
/** tauri-plugin-updater/updater.rs:1448: outer base64, then minisign-verify::verify(..., true). */
export function verifyMinisign(data: Uint8Array, releaseSignature: string, pubKey: string): void {
  const publicLines = text(pubKey).split(/\r?\n/);
  if (publicLines.length < 2) throw invalid();
  const key = decode(publicLines[1]!);
  if (key.length !== 42) throw invalid();
  if (key.subarray(0, 2).toString() !== 'Ed' && key.subarray(0, 2).toString() !== 'ED') throw new Error('This signature algorithm is not supported by this implementation');
  const lines = text(releaseSignature).split(/\r?\n/);
  if (lines.length < 4) throw invalid();
  const sig = decode(lines[1]!), global = decode(lines[3]!);
  if (sig.length !== 74 || global.length !== 64 || !lines[2]!.startsWith('trusted comment: ')) throw invalid();
  const algorithm = sig.subarray(0, 2).toString();
  if (algorithm !== 'Ed' && algorithm !== 'ED') throw new Error('This signature algorithm is not supported by this implementation');
  if (!key.subarray(2, 10).equals(sig.subarray(2, 10))) throw new Error('The signature was created with a different key than the one provided');
  const publicKey = createPublicKey({ key: Buffer.concat([Buffer.from('302a300506032b6570032100', 'hex'), key.subarray(10)]), format: 'der', type: 'spki' });
  const signature = sig.subarray(10);
  if (!verify(null, algorithm === 'ED' ? blake2b(data) : data, publicKey, signature) || !verify(null, Buffer.concat([signature, Buffer.from(lines[2]!.slice(17))]), publicKey, global)) {
    throw new Error('The signature verification failed');
  }
}
