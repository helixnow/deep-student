#!/usr/bin/env node
// Writes <suite>.provider.json for every chatanki suite: the static X5 sidecar form of the
// `w0.directive` rule in README.md. Per scenario, in request order:
//   each chat_v2_send_message: rounds[k] as one tool_calls stream per round, then `final` (finish=stop);
//   after the first reply in a session created without a title: one non-stream JSON answer for the
//   session metadata call (pipeline/summary.rs: call_agent_chat_title_raw_prompt falls back to
//   model2_config_id, force_json). A title passed to chat_v2_create_session locks it
//   (manage_session.rs create_session_in_db: title_locked = title.is_some()), so no call is made.
// Chunks follow host/e2e/streaming/wave0/llm-service.ts frameJson/completionJson byte for byte.
// Scenarios whose directive embeds `${n…}` (ids/versions known only at run time) carry
// `llm: "w0.directive"` and need X5's dynamic script; no static answer is written for them.
//   node host/plugins/chatanki/equivalence/__fixtures__/provider-from-directives.mjs [--check]
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = fileURLToPath(new URL('..', import.meta.url));
const ID = 'chatcmpl-x5-fixed', CREATED = 1_700_000_000;
const SSE = { 'content-type': 'text/event-stream', 'cache-control': 'no-cache' };
const JSON_HEADERS = { 'content-type': 'application/json' };
const PREFIX = 'W0_DIRECTIVE ';
export const METADATA = { title: 'W0 制卡助手', tags: ['W0', '制卡', '模板'] };

const data = value => `data: ${JSON.stringify(value)}\n\n`;
const chunk = (model, delta, finish) => ({ id: ID, object: 'chat.completion.chunk', created: CREATED, model,
  choices: [{ index: 0, delta, finish_reason: finish }] });
const usage = (model, prompt, completion) => ({ id: ID, object: 'chat.completion.chunk', created: CREATED, model, choices: [],
  usage: { prompt_tokens: prompt, completion_tokens: completion, total_tokens: prompt + completion } });

function toolRound(model, calls) {
  return { status: 200, headers: SSE, chunks: [
    ...calls.map((call, index) => data(chunk(model, { tool_calls: [{ index, id: call.id, type: 'function',
      function: { name: call.name, arguments: JSON.stringify(call.arguments) } }] }, null))),
    data(chunk(model, {}, 'tool_calls')), data(usage(model, 9, 3)), 'data: [DONE]\n\n'] };
}
function finalRound(model, content) {
  return { status: 200, headers: SSE, chunks: [data(chunk(model, { content }, null)), data(chunk(model, {}, 'stop')),
    data(usage(model, 12, 4)), 'data: [DONE]\n\n'] };
}
function metadataAnswer(model) {
  return { status: 200, headers: JSON_HEADERS, chunks: [JSON.stringify({ id: ID, object: 'chat.completion', created: CREATED, model,
    choices: [{ index: 0, message: { role: 'assistant', content: JSON.stringify(METADATA) }, finish_reason: 'stop' }],
    usage: { prompt_tokens: 20, completion_tokens: 8, total_tokens: 28 } })] };
}

export function responsesFor(scenario) {
  const models = new Map(), sessions = new Map();
  const responses = [];
  for (const [index, step] of scenario.steps.entries()) {
    if (step.cmd === 'save_api_configurations') for (const config of step.args.configs) models.set(config.id, config.model);
    if (step.cmd === 'chat_v2_create_session') sessions.set(index, { metadataPending: step.args.title == null });
    if (step.cmd !== 'chat_v2_send_message') continue;
    const { content, options, sessionId } = step.args.request;
    const session = sessions.get(Number(/^\$\{(\d+)\.id\}$/.exec(sessionId)?.[1]));
    if (!session) throw new Error(`${scenario.id}: sessionId ${sessionId} is not a chat_v2_create_session step`);
    if (!content.startsWith(PREFIX)) throw new Error(`${scenario.id}: send_message without ${PREFIX.trim()}`);
    const directive = JSON.parse(content.slice(PREFIX.length));
    const model = models.get(options.modelId);
    if (directive.v !== 1 || typeof model !== 'string') throw new Error(`${scenario.id}: unsupported directive or model ${options.modelId}`);
    for (const calls of directive.rounds) responses.push(toolRound(model, calls));
    responses.push(finalRound(model, directive.final));
    if (session.metadataPending) { responses.push(metadataAnswer(model)); session.metadataPending = false; }
  }
  return responses;
}

export function sidecarFor(suite) {
  const out = { note: 'W21: static form of the README w0.directive rule, generated by __fixtures__/provider-from-directives.mjs; per scenario in request order: tool_calls rounds, final, then the session metadata JSON after the first reply of an untitled session.' };
  for (const scenario of suite.scenarios) {
    const dynamic = scenario.steps.some(step => step.cmd === 'chat_v2_send_message' && step.args.request.content.includes('${'));
    if (dynamic !== (scenario.llm === 'w0.directive')) throw new Error(`${scenario.id}: llm must be "w0.directive" exactly when the directive has run-time references`);
    if (!dynamic) out[scenario.id] = responsesFor(scenario);
  }
  return JSON.stringify(out, null, 2) + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const name of readdirSync(DIR).filter(n => n.endsWith('.json') && !n.endsWith('.provider.json') && !n.endsWith('.sidecar.json')).sort()) {
    const target = join(DIR, name.replace(/\.json$/, '.provider.json'));
    const text = sidecarFor(JSON.parse(readFileSync(join(DIR, name), 'utf8')));
    if (existsSync(target) && readFileSync(target, 'utf8') === text) continue;
    stale++;
    if (check) console.error(`stale: ${target}`);
    else writeFileSync(target, text);
  }
  if (check && stale) process.exitCode = 1;
}
